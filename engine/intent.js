/**
 * engine/intent.js — что имел в виду менеджер: одобрение, правка, вопрос,
 * да/нет, команда завершения. Пока решают списки фраз; LLM-классификатор
 * работает в тени (logIntentClassificationShadow) и только логирует.
 */
const { callAgent } = require('../agentRunner');

// Раньше в системе не было НИКАКОГО способа для менеджера сказать "закончи
// сессию прямо сейчас" — фраза вроде "заверши сессию" просто уходила как
// обычный текст в planner/diagnostic, который не находил в ней ответов на
// свои уточняющие вопросы и переспрашивал то же самое по кругу. Теперь такая
// команда распознаётся явно и сразу приводит к FINAL_OUTPUT, независимо от
// того, в каком состоянии находится сделка (даже посреди уточняющих вопросов).
const END_SESSION_PHRASES = [
  'заверши сессию', 'заверши сеанс', 'заверши диалог',
  'закрой сессию', 'закрой сеанс',
  'закрыть сессию', 'закрыть сеанс',
  'заверши', 'закончи сессию', 'закончить сессию',
  'завершить сессию', 'заканчиваем', 'на сегодня хватит', 'стоп сессия'
];

function isEndSessionCommand(text) {
  const raw = (text || '').trim().toLowerCase().replace(/[.!?,;:]+$/g, '');
  return END_SESSION_PHRASES.includes(raw);
}

// Раньше ЛЮБОЕ сообщение менеджера в состоянии COMPOSING (после показа касаний)
// уходило сразу на формальную проверку reviewer'ом — даже если менеджер написал
// содержательную правку вроде "слишком в лоб, нужно мягче". Reviewer проверяет
// по чек-листу (стоп-слова, персонализация и т.д.), а не по вкусовым пожеланиям
// менеджера, поэтому такой фидбэк тихо терялся, и одобрялся неизменённый вариант.
//
// Первая версия проверки требовала ТОЧНОГО совпадения всего сообщения с фразой
// согласия — это защищало от ложных срабатываний ("в целом норм, но..." больше
// не считалось согласием из-за слова "норм"), но оказалась слишком строгой:
// естественные фразы вроде "хорошо, меня устраивает" или "понял, ок" не совпадали
// один-в-один ни с чем в списке и снова уходили на "доработку" — сессия
// зацикливалась, потому что composer каждый раз возвращал то же самое, а
// согласие никогда не засчитывалось.
//
// Теперь: сообщение разбивается на смысловые части (по запятым/точкам/тире),
// и согласием считается, если КАЖДАЯ часть — это фраза одобрения из списка.
// Отдельно проверяются явные сигналы правки ("но", "хотя", "добавь", "смягчи"
// и т.п.) — если такой сигнал есть где-то в сообщении, это правка, а не
// согласие, даже если рядом есть слово "хорошо" или "норм".
const PURE_APPROVAL_PHRASES = new Set([
  'ок', 'окей', 'окай', 'ok', 'okay', 'да', 'ага', 'угу',
  'супер', 'отлично', 'класс', 'здорово', 'хорошо', 'норм', 'нормально',
  'принято', 'согласен', 'согласна', 'одобряю', 'одобрено',
  'погнали', 'го', 'вперед', 'вперёд', 'давай', 'запускай', 'запускаем', 'дальше',
  'понял', 'поняла', 'ясно', 'ладно', 'идеально', 'верно', 'подходит',
  'устраивает', 'меня устраивает',
  'все ок', 'всё ок', 'все супер', 'всё супер', 'все хорошо', 'всё хорошо',
  'все норм', 'всё норм', 'все отлично', 'всё отлично', 'все верно', 'всё верно',
  'все устраивает', 'всё устраивает', 'все подходит', 'всё подходит'
]);

const REVISION_SIGNAL_WORDS = new Set(['но', 'однако', 'хотя', 'кроме', 'зато']);

const REVISION_SIGNAL_PHRASES = [
  'добавь', 'добавьте', 'поменяй', 'поменяйте', 'убери', 'уберите',
  'замени', 'замените', 'нужно чтобы', 'нужно бы', 'надо чтобы',
  'было бы лучше', 'слишком', 'не хватает', 'хотелось бы', 'хочу чтобы',
  'а также', 'ещё используй', 'еще используй', 'обычно использую', 'я использую',
  'смягчи', 'сократи', 'удлини', 'исправь', 'поправь'
];

function isPureApproval(text) {
  const raw = (text || '').trim().toLowerCase();
  if (!raw) return false;
  // Токенизация — чтобы "но" ловилось только как отдельное слово, а не как
  // часть другого слова (например "давно").
  const tokens = raw.split(/[^a-zа-яё0-9]+/i).filter(Boolean);
  if (tokens.some(t => REVISION_SIGNAL_WORDS.has(t))) return false;
  if (REVISION_SIGNAL_PHRASES.some(p => raw.includes(p))) return false;
  const clauses = raw
    .split(/[.,!;:\-—]+/)
    .map(s => s.trim())
    .filter(Boolean);
  if (!clauses.length) return false;
  return clauses.every(clause => PURE_APPROVAL_PHRASES.has(clause));
}

// Этапы оценки и стратегии: «ок» или просьба идти дальше («давай стратегию»,
// «пиши касания») — переход к следующему шагу; всё остальное — правка или
// новые факты, по которым результат пересобирается (живой тест 2026-11-13:
// «перепиши оценку с учётом сроков» молча запустило стратегию).
const GO_NEXT_RE = /^(ок|окей|да|давай|дальше|го|хорошо|согласен|согласна)?[\s,.!]*((давай|делай|сделай|составь|пиши|напиши|переходи(м)?|перейди|к)\s+)*(стратеги[а-яё]*|касани[а-яё]*)[\s.!]*$/i;
function isGoAhead(text) {
  const raw = String(text || '').trim();
  return isPureApproval(raw) || GO_NEXT_RE.test(raw);
}

// Определяет, является ли сообщение менеджера ВОПРОСОМ к агенту (просьбой
// подсказать/посоветовать), а не инструкцией по правке текста касаний.
// Раньше такие сообщения ("может продолжить с Александром?", "что ответить
// на 'дорого'?") уходили в composer как manager_feedback — composer не умеет
// отвечать на вопросы, он умеет только переписывать касания, поэтому на
// таком вводе он просто возвращал прежний текст почти без изменений, и
// сессия зацикливалась, потому что менеждер продолжал получать один и тот
// же результат на разные переформулировки вопроса.
const QUESTION_MARKER_PHRASES = [
  'может ', 'можно ли', 'стоит ли', 'как быть', 'что делать', 'что если',
  'как мне', 'как поступить', 'что ответить', 'что посоветуешь', 'что посоветуете',
  'как думаешь', 'как думаете', 'а если', 'нужно ли', 'правильно ли', 'как лучше'
];

function isManagerQuestion(text) {
  const raw = (text || '').trim().toLowerCase();
  if (!raw) return false;
  if (raw.includes('?')) return true;
  return QUESTION_MARKER_PHRASES.some((p) => raw.includes(p));
}

// Проверка ответа менеджера на наш уточняющий вопрос "скорректировать касания
// с учётом этого?" — отдельная от isPureApproval, потому что здесь речь не
// об одобрении касаний, а именно о да/нет на конкретный вопрос.
const AFFIRMATIVE_PHRASES = new Set([
  'да', 'ага', 'угу', 'давай', 'конечно', 'обязательно', 'нужно', 'хочу',
  'скорректируй', 'скорректируйте', 'скорректировать', 'поправь', 'поправьте',
  'да, скорректируй', 'да скорректируй', 'да, нужно', 'да нужно'
]);

const NEGATIVE_PHRASES = new Set([
  'нет', 'не', 'не надо', 'не нужно', 'не стоит',
  'оставь как есть', 'оставьте как есть', 'оставить как есть'
]);

function isAffirmativeResponse(text) {
  const raw = (text || '').trim().toLowerCase().replace(/[.!]+$/g, '');
  if (!raw) return false;
  if (AFFIRMATIVE_PHRASES.has(raw)) return true;
  if (raw.startsWith('да') && !raw.startsWith('давно')) return true;
  if (raw.includes('скорректир') || raw.includes('поправ')) return true;
  return false;
}

function isNegativeResponse(text) {
  const raw = (text || '').trim().toLowerCase().replace(/[.!]+$/g, '');
  if (!raw) return false;
  if (NEGATIVE_PHRASES.has(raw)) return true;
  if (raw.startsWith('нет')) return true;
  if (raw.includes('не надо') || raw.includes('не нужно') || raw.includes('оставь как есть') || raw.includes('оставьте как есть')) return true;
  return false;
}

// Блок 3 (сессия 3, ТЕНЕВОЙ РЕЖИМ) — маппинг категорий LLM-классификатора
// на то, что фактически решил regex в текущей точке кода. Порядок
// проверки должен зеркалить порядок проверок в самом COMPOSING-кейсе:
// isPureApproval проверяется раньше isManagerQuestion, поэтому если
// сообщение прошло как approval — question уже не имеет значения.
function regexIntentLabel(isApproval, isQuestion) {
  if (isApproval) return 'approval';
  if (isQuestion) return 'question';
  return 'revision'; // всё остальное сейчас уходит в composer как правка
}


// Fire-and-forget: НЕ await'ится в вызывающем коде, чтобы не добавлять
// задержку к ответу менеджеру. Любая ошибка (сеть, парсинг) молча
// проглатывается здесь же — это диагностический слой, а не часть
// критического пути, он не должен иметь возможности уронить сессию.
function logIntentClassificationShadow(managerInput, isApproval, isQuestion, dealId) {
  const regexLabel = regexIntentLabel(isApproval, isQuestion);
  callAgent('intent_classifier', { text: managerInput }, 200)
    .then((result) => {
      const llmLabel = result?.intent_classifier_output?.intent || result?.intent;
      if (!llmLabel) return; // сломанный/неожиданный ответ — не наш критический путь, просто пропускаем
      if (llmLabel !== regexLabel) {
        console.warn(
          `[intent-shadow] Расхождение (сделка: ${dealId || 'unknown_deal'}): ` +
          `сообщение "${managerInput}" — regex решил "${regexLabel}", LLM решила "${llmLabel}". ` +
          `Реальное поведение сейчас определяет regex (теневой режим, ничего не меняется автоматически).`
        );
      }
    })
    .catch((err) => {
      console.warn(`[intent-shadow] Не удалось получить теневую классификацию (сделка: ${dealId || 'unknown_deal'}): ${err.message}`);
    });
}

module.exports = {
  isGoAhead,
  isEndSessionCommand,
  isPureApproval,
  isManagerQuestion,
  isAffirmativeResponse,
  isNegativeResponse,
  logIntentClassificationShadow,
};
