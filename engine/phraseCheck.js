// («у меня таких полномочий нет, попробую согласовать»). Порядок: уступка через полномочия → «если получится —
// заключаемся?».
const CONCESSION_RE = /(нет|нету) (таких |этих )?полномочий|полномочий (у меня )?нет|попробую (согласовать|убедить|выбить|договориться с руководител)|согласовать с руководител|уступк/i;
function closeBeforeConcession(text) {
  const t = String(text || '');
  const k = t.search(CONCESSION_RE);
  if (k < 0) return false;
  const c = t.search(CLOSE_Q_RE);
  return c >= 0 && c < k;
}
const CLOSE_BEFORE_CONCESSION_FIX = 'Закрывающий вопрос — ПОСЛЕ уступки, а не до (владелец 16.11): сначала «У меня таких полномочий нет, но попробую согласовать с руководителем», затем выгода и закрытие: «Если получится — заключаемся? Тогда ставлю вас в ближайший слот, и вывеска будет у вас к открытию». «По рукам?» до предложения звучит как давление.';
const POSITIVE_MOOD_RE = /в целом (вс[её] )?(устраивает|нравится|подходит|ок)|(нам |ему |ей )?(всё )?нравится|понравил|по делу|я бы у вас|сделаете [^.!?\n]{0,20}(—|-|и) (подпис|закаж|берём|заключ)|подписываем (на этой неделе|до)|готовы (подписать|заключ)/i;
const CLOSE_FIX = 'Закрывающий вопрос («по рукам?», «оформляемся?») — только после «температуры» (владелец 16.11): сначала «Как вам в целом?» [пауза, выслушать] → если в целом ок — «По рукам? Заключаемся?». Не в одной фразе.';
const WEEKDAY_FIX = 'Убрать «если удобнее в будни» / «не отвлекаю в выходной» — касание не на выходной.';
const REFERENCE_RE = /(дам|дать|дадим|пришлю|поделюсь|познаком\w*|свяж\w*)[^.!?\n]{0,40}(контакт|телефон|номер)[^.!?\n]{0,50}(клиент|заказчик|владел)|(контакт|телефон)[^.!?\n]{0,15}(нашего|наших|одного из)[^.!?\n]{0,15}(клиент|заказчик)|(клиент|заказчик)[^.!?\n]{0,40}готов[^.!?\n]{0,20}(рассказать|поговорить|пообщаться)/i;
const REFERENCE_SRC_RE = /(контакт|телефон|номер)[^.!?\n]{0,40}(клиент|заказчик)|готов[^.!?\n]{0,20}(дать )?рекомендац|клиент[^.!?\n]{0,30}готов[^.!?\n]{0,20}(рассказать|поговорить)/i;
const REFERENCE_FIX = 'Убрать предложение дать контакт нашего клиента / «клиент готов рассказать» — в материалах менеджера такого клиента нет, это выдумка (владелец 15.11). Доверие — реальными фактами: договор, гарантия по договору, выезд по гарантии за 3 рабочих дня, проверка с подсветкой до отгрузки, кейсы из базы.';
// Владелец 17.11, «Сильный оффер» (файл 30), ошибка 3: расплывчатые слова — клиент пропускает мимо ушей.
// Только если в той же фразе нет конкретики (цифры, даты, факта компании).
const VAGUE_RE = /(сделаем|делаем|сделаю|выполним)\s+(вс[её]\s+)?(надёжно|надежно|качественно|быстро|выгодно)|качественн(ые|ыми) материал|высок(ое|ого|им) качеств|лучшее качество|индивидуальн(ый|ого|ым) подход|в кратчайшие сроки|быстрые сроки|выгодн(ые|ая|ую) цен|оптимальн(ую|ая) цен|доступн(ые|ая|ую) цен/i;
const CONCRETE_RE = /\d|договор|(?<![а-яё])отк(?![а-яё])|гаранти|902|производств|слот|кейс|личн(ый|ого) менеджер|визуализац|монтаж[а-я]* (наш|бригад)/i;
function vagueOffer(text) {
  return String(text || '').split(/(?<=[.!?\n])/).some((x) => VAGUE_RE.test(x) && !CONCRETE_RE.test(x));
}
const VAGUE_FIX = 'Расплывчатый оффер (владелец 17.11, файл 30, ошибка 3): «сделаем быстро / качественные материалы / выгодная цена / индивидуальный подход» клиент пропускает мимо ушей. Заменить конкретикой из фактов компании и результатом клиента: дата из расчёта, ОТК до отгрузки — точно по ТЗ, гарантия в договоре с выездом за 3 рабочих дня, цена КП держится 2 месяца, личный менеджер от первой встречи до монтажа.';

function findBannedPhrases(messages, sourceText = '') {
  const out = [];
  (messages || []).forEach((m, i) => {
    const text = touchText(m);
    const fixes = BANNED.filter((b) => (b.test ? b.test(text) : b.re.test(text))).map((b) => b.fix);
    // Прогон 15.11 «Fresh Bowl»: «могу дать контакт клиента, который расскажет» — выдумка, если менеджер
    // в материалах такого клиента не называл (владелец 15.11: выдуманные не нужны).
    if (REFERENCE_RE.test(text) && !REFERENCE_SRC_RE.test(String(sourceText || ''))) fixes.push(REFERENCE_FIX);
    for (const x of LIVE_1511) if (x.re.test(text)) fixes.push(x.fix);
    // Живой прогон 16.11: ИИ-штампы, «пусть знает», закрывающий вопрос без «температуры».
    for (const x of LIVE_1611) if (x.re.test(text)) fixes.push(x.fix);
    // Владелец 17.11: «Подписываем?» без температуры — по контексту: если клиент уже показал настрой (в целом
    // устраивает, нравится, торгуется с условием покупки), это призыв к действию, не ошибка.
    if (closeWithoutTemperature(text) && !POSITIVE_MOOD_RE.test(String(sourceText || '').slice(-1500))) fixes.push(CLOSE_FIX);
    if (closeBeforeConcession(text)) fixes.push(CLOSE_BEFORE_CONCESSION_FIX);
    if (vagueOffer(text)) fixes.push(VAGUE_FIX);
    // «Чем вы лучше?» — отвечать результатом: «вы получаете …» (владелец 15.11).
    if (BETTER_Q_RE.test(String(sourceText || '')) && BETTER_ANSWER_RE.test(text) && !RESULT_RE.test(text)) fixes.push(BETTER_FIX);
    // «в будни» / «не отвлекаю в выходной» — только для касания на выходной (живой прогон 15.11).
    if (/в будни|не отвлекаю в выходн|в выходной не отвлека/i.test(text) && !/выходн|\(сб\)|\(вс\)|суббот|воскресен/i.test(String(m?.timing || ''))) fixes.push(WEEKDAY_FIX);
    const unknown = unknownCases(text, sourceText);
    if (unknown.length) fixes.push(UNKNOWN_CASE_FIX(unknown));
    if (fixes.length) out.push({ touchpoint_number: Number(m?.touchpoint_number ?? i + 1), fixes });
  });
  return out;
}

// Накладывает программную проверку на ответ reviewer'а: касание с запрещённой
// фразой — НА ДОРАБОТКУ, общий вердикт — не ОДОБРЕНО.
function applyPhraseCheck(reviewerOutput, messages, sourceText = "") {
  const hits = findBannedPhrases(messages, sourceText);
  if (!hits.length || !reviewerOutput || typeof reviewerOutput !== 'object') return { reviewerOutput, hits };
  const r = reviewerOutput.reviewer_output && !reviewerOutput.messages_reviewed ? reviewerOutput.reviewer_output : reviewerOutput;
  const reviewed = Array.isArray(r.messages_reviewed) ? r.messages_reviewed : (r.messages_reviewed = []);
  for (const h of hits) {
    let m = reviewed.find((x) => Number(x?.touchpoint_number) === h.touchpoint_number);
    if (!m) { m = { touchpoint_number: h.touchpoint_number }; reviewed.push(m); }
    if (m.verdict === 'ОДОБРЕНО' || !m.verdict) m.verdict = 'НА ДОРАБОТКУ';
    m.failed_criteria = [...new Set([...(m.failed_criteria || []), 'no_stop_words'])];
    m.code_checked = true;
    m.fix_instructions = [m.fix_instructions, ...h.fixes].filter(Boolean).join(' ');
  }
  if (r.verdict === 'ОДОБРЕНО' || !r.verdict) r.verdict = 'НА ДОРАБОТКУ';
  return { reviewerOutput, hits };
}

module.exports = { findBannedPhrases, applyPhraseCheck, BANNED, vagueOffer };
