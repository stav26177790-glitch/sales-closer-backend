// Закрывающий вопрос («по рукам?», «оформляемся?», «заключаемся?») — только после «температуры»:
// «Как вам в целом?» [пауза] → если ок → «по рукам?». Не в одной фразе и не без вопроса о температуре.
// + симулятор 16.11: «готовы подписывать сегодня?», «могу выставлять счёт?», «согласовать дату подписания».
const CLOSE_Q_RE = /по рукам\s*\?|подписываем(ся)?( сегодня)?\s*\?|фиксируем( договор)?\s*\?|оформляемся\s*\?|заключаемся\s*\?|готовы (подписывать|подписать|заключаться|заключить)[^?.!\n]{0,30}\?|могу выставлять сч[её]т\s*\?|согласовать дату (подписания|договора)/i;
const TEMP_Q_RE = /как вам( в целом| такой вариант)?\s*[?—–-]|что скажете|откликается|как ощущения/i;
function closeWithoutTemperature(text) {
  const t = String(text || '');
  const c = t.search(CLOSE_Q_RE);
  if (c < 0) return false;
  const before = t.slice(0, c);
  const tm = [...before.matchAll(new RegExp(TEMP_Q_RE.source, 'gi'))].pop();
  if (!tm) return true;
  const between = before.slice(tm.index + tm[0].length);
  return !/\[пауза|\[выслуш|\[если|если (в целом )?(вс[её] )?(ок|устраивает|нравится|подходит|да)|\n\s*\n/i.test(between);
}
