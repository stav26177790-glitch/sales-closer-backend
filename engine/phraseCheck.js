const BETTER_Q_RE = /чем (вы|ваша компания|вы там) лучше|чем отличаетесь|почему (должны )?(выбрать )?(именно )?вас/i;
const BETTER_ANSWER_RE = /(договор|гаранти)[^]{0,200}(выезд|провер|подсветк)|чем мы лучше|чем лучше тех/i;
const RESULT_RE = /вы получ|получите|получаете|у вас будет/i;
const BETTER_FIX = 'На «чем вы лучше» — не только перечень фактов, а результат для клиента (владелец 15.11): факт → «и вы получаете» → результат в его словах. Например: «…— и вы получаете вывеску, которая горит с первого дня, и подрядчика, который через три месяца берёт трубку».';
const WEEKDAY_FIX = 'Убрать «если удобнее в будни» / «не отвлекаю в выходной» — касание не на выходной.';
const REFERENCE_RE = /(дам|дать|дадим|пришлю|поделюсь|познаком\w*|свяж\w*)[^.!?\n]{0,40}(контакт|телефон|номер)[^.!?\n]{0,50}(клиент|заказчик|владел)|(контакт|телефон)[^.!?\n]{0,15}(нашего|наших|одного из)[^.!?\n]{0,15}(клиент|заказчик)|(клиент|заказчик)[^.!?\n]{0,40}готов[^.!?\n]{0,20}(рассказать|поговорить|пообщаться)/i;
const REFERENCE_SRC_RE = /(контакт|телефон|номер)[^.!?\n]{0,40}(клиент|заказчик)|готов[^.!?\n]{0,20}(дать )?рекомендац|клиент[^.!?\n]{0,30}готов[^.!?\n]{0,20}(рассказать|поговорить)/i;
const REFERENCE_FIX = 'Убрать предложение дать контакт нашего клиента / «клиент готов рассказать» — в материалах менеджера такого клиента нет, это выдумка (владелец 15.11). Доверие — реальными фактами: договор, гарантия по договору, выезд по гарантии за 3 рабочих дня, проверка с подсветкой до отгрузки, кейсы из базы.';
function findBannedPhrases(messages, sourceText = '') {
  const out = [];
  (messages || []).forEach((m, i) => {
    const text = touchText(m);
    const fixes = BANNED.filter((b) => (b.test ? b.test(text) : b.re.test(text))).map((b) => b.fix);
    // Прогон 15.11 «Fresh Bowl»: «могу дать контакт клиента, который расскажет» — выдумка, если менеджер
    // в материалах такого клиента не называл (владелец 15.11: выдуманные не нужны).
    if (REFERENCE_RE.test(text) && !REFERENCE_SRC_RE.test(String(sourceText || ''))) fixes.push(REFERENCE_FIX);
    for (const x of LIVE_1511) if (x.re.test(text)) fixes.push(x.fix);
    // «Чем вы лучше?» — отвечать результатом: «вы получаете …» (владелец 15.11).
    if (BETTER_Q_RE.test(String(sourceText || '')) && BETTER_ANSWER_RE.test(text) && !RESULT_RE.test(text)) fixes.push(BETTER_FIX);
    // «в будни» / «не отвлекаю в выходной» — только для касания на выходной (живой прогон 15.11).
    if (/в будни|не отвлекаю в выходн|в выходной не отвлека/i.test(text) && !/выходн|\(сб\)|\(вс\)|суббот|воскресен/i.test(String(m?.timing || ''))) fixes.push(WEEKDAY_FIX);
    const unknown = unknownCases(text, sourceText);
    if (unknown.length) fixes.push(UNKNOWN_CASE_FIX(unknown));
    if (fixes.length) out.push({ touchpoint_number: Number(m?.touchpoint_number ?? i + 1), fixes });
  });
  return out;
}

// Накладывает программную проверку на ответ reviewer'а: касание с запрещённой
// фразой — НА ДОРАБОТКУ, общий вердикт — не ОДОБРЕНО.
function applyPhraseCheck(reviewerOutput, messages, sourceText = "") {
  const hits = findBannedPhrases(messages, sourceText);
  if (!hits.length || !reviewerOutput || typeof reviewerOutput !== 'object') return { reviewerOutput, hits };
  const r = reviewerOutput.reviewer_output && !reviewerOutput.messages_reviewed ? reviewerOutput.reviewer_output : reviewerOutput;
  const reviewed = Array.isArray(r.messages_reviewed) ? r.messages_reviewed : (r.messages_reviewed = []);
  for (const h of hits) {
    let m = reviewed.find((x) => Number(x?.touchpoint_number) === h.touchpoint_number);
    if (!m) { m = { touchpoint_number: h.touchpoint_number }; reviewed.push(m); }
    if (m.verdict === 'ОДОБРЕНО' || !m.verdict) m.verdict = 'НА ДОРАБОТКУ';
    m.failed_criteria = [...new Set([...(m.failed_criteria || []), 'no_stop_words'])];
    m.code_checked = true;
    m.fix_instructions = [m.fix_instructions, ...h.fixes].filter(Boolean).join(' ');
  }
  if (r.verdict === 'ОДОБРЕНО' || !r.verdict) r.verdict = 'НА ДОРАБОТКУ';
  return { reviewerOutput, hits };
}

module.exports = { findBannedPhrases, applyPhraseCheck, BANNED };
