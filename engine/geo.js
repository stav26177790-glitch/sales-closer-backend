/**
 * engine/geo.js — где объект: Москва (правила 902-ПП) или нет. Одно определение на весь Клоузер.
 *
 * Аудит 18.11: «не Москва» было объявлено дважды — в плане касаний (с городами Подмосковья) и в проверках
 * касаний (без них). Для Мытищ план не звал по 902-ПП, а проверки требовали московских запретов
 * («световой короб нельзя», «баннер на фасад нельзя») — у «Гаража 77» как раз световой короб.
 */
const MOSCOW_RE = /москв|мск([^а-яё]|$)|метро(?![а-яё])|м\.\s?[А-ЯЁ]|902-?пп/i;
const NOT_MOSCOW_RE = /(област|обл\.|подмосков|край\b|республик|санкт-петербург|спб|петербург|казан|екатеринбург|новосибирск|краснодар|нижн[а-яё]* новгород|самар|ростов|уф[аеы]\b|перм|воронеж|тул[аеы]\b|твер|калуг|ярослав|владимир|рязан|химк|подольск|люберц|мытищ|балаших|красногорск|одинцов|королёв|королев)/i;

const s = (t) => String(t || '');
/** Москва названа и другой город / область — нет. */
const isMoscow = (text) => MOSCOW_RE.test(s(text)) && !NOT_MOSCOW_RE.test(s(text));
/** Москва или город не ясен — московские правила на всякий случай действуют. */
const moscowOrUnknown = (text) => !NOT_MOSCOW_RE.test(s(text));
/** Явно не Москва: Москвы не видно, другой город / область названы. */
const clearlyNotMoscow = (text) => !MOSCOW_RE.test(s(text)) && NOT_MOSCOW_RE.test(s(text));

module.exports = { MOSCOW_RE, NOT_MOSCOW_RE, isMoscow, moscowOrUnknown, clearlyNotMoscow };
