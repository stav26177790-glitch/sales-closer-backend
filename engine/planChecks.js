const { isWorkingDay } = require('./timeline');
/**
 * engine/planChecks.js — проверки касаний по плану (владелец 14.11).
 *
 * 1. «Последний шанс» — последнее касание цепочки: попросить сказать как есть,
 *    чтобы не тратить время клиента. Этот вопрос — ТОЛЬКО в последнем касании
 *    (живой «Зерно 7»: «есть ли у меня реальный шанс?» стоял и после того, как
 *    клиент ожил), и в последнем он обязателен.
 * 2. Компромисс при «дорого»: «подберу варианты под ваш бюджет, чтобы вы не
 *    переплачивали» → альтернативы (меньше размер, реже диоды, пластиковый борт…).
 *    Владелец: «нужно использовать логику компромисса — „есть риск“: менеджер
 *    должен объяснить клиенту, что мы отходим от ТЗ». Альтернатива без слов о
 *    риске / отходе от ТЗ — на доработку.
 */

const LAST_CHANCE_RE = /(есть ли|остал[а-яё]* ли)[^.?!]{0,30}шанс|скажите (как есть|прямо|в открытую|открыто)|как есть[^.?!]{0,40}(актуал|интерес|нужн)|не (буду|стану) (больше )?(вас )?(беспокоить|отвлекать|тратить)|не тратить (больше )?ваше время|что я сделал не так/i;
const LAST_CHANCE_HINT = '«Марина, скажите как есть: проект ещё актуален? Если нет — не буду больше отвлекать, чтобы не тратить ваше время. Если да — договоримся о следующем шаге.» Можно мягкую провокацию: «Понимаю, что моё решение, возможно, не подошло. Подскажите, что стало причиной?»';

const ALT_RE = /под ваш бюджет|уложиться в бюджет|чтобы вы не переплачивали|подешевле|уменьш[а-яё]* (размер|высот|букв|логотип)|буквы поменьше|пластиков[а-яё]* борт|расстановк[а-яё]* диод|реже (шаг|диод|постав)|без подсветки|подсвет[а-яё]* только логотип|короб вместо|вместо алюмини/i;
const RISK_RE = /риск|отход[а-яё]* от|отступ[а-яё]* от|от (тз|техзадани|исходного (задания|проекта))|компромисс|(будет|станет|получится) (хуже|меньше|проще|тусклее|неравномерн)|ценой (того|чего)/i;
const COMPROMISE_FIX = 'Альтернатива подешевле — это отход от ТЗ (логика компромисса): прямо сказать клиенту, что мы отходим от ТЗ и в чём риск. Например: «Чтобы вы не переплачивали, подберу варианты под ваш бюджет. Но скажу честно: это отход от ТЗ — если уменьшить буквы, вывеску хуже видно издалека; если реже поставить диоды, может быть неравномерное свечение». Новых цен не называть — «посчитаю и пришлю».';

// Москва, 902-ПП (владелец 14.11): буквы без подсветки — нельзя; короб — только инкрустация /
// псевдоинкрустация. Город не всегда известен: проверяем, если в переписке нет явного «не Москва».
const NOT_MOSCOW_RE = /(област|обл\.|подмосков|край\b|республик|санкт-петербург|спб|петербург|казан|екатеринбург|новосибирск|краснодар|нижн[а-яё]* новгород|самар|ростов|уф[аеы]\b|перм|воронеж|тул[аеы]\b|твер|калуг|ярослав|владимир|рязан)/i;
const UNLIT_RE = /(буквы|вывеск[а-яё]*|надпись)[^.!?]{0,30}без подсветки|без подсветки[^.!?]{0,20}(букв|вывеск)|несветов/i;
const BOX_RE = /(световой |лайт)?короб[а-яё]* вместо|вместо (отдельных )?букв[^.!?]{0,20}короб/i;
const INLAY_RE = /инкрустац/i;
// Временная вывеска (владелец 14.11): в Москве — только внутри помещения.
const BANNER_RE = /баннер|временн[а-яё]* вывеск/i;
const INSIDE_RE = /внутри|изнутри|в витрин|в помещени|в зале|в окн/i;
const MOSCOW_FIXES = {
  banner: 'Временная вывеска в Москве — только внутри помещения (902-ПП запрещает баннерную ткань на фасаде): сказать «временную вывеску поставим внутри, в витрине / в зале». Если объект точно не в Москве — уточнить город.',
  unlit: 'Буквы без подсветки в Москве предлагать нельзя (902-ПП). Убрать этот вариант; если объект точно не в Москве — сначала уточнить город.',
  box: 'Короб вместо букв в Москве — только по технологии «инкрустация» или «псевдоинкрустация» (902-ПП): так и сказать, иначе не предлагать.'
};

const textOf = (m) => [m?.body, m?.attachment?.content].filter(Boolean).join('\n');

// Деньги — только звонок или Zoom (владелец 14.11). В письменном касании — не обсуждать
// бюджет, «дорого», скидки, варианты под бюджет, стоимость; предложить созвониться.
// Цена из КП как факт («по КП 185 000 ₽») — можно.
const MONEY_TALK_RE = /из чего складывается|что стоит за цен|бюджет|дорог|дешевл|скидк|переплач|стоимост|сколько (будет )?стоит|под ваш бюджет|подешевле|уложиться в/i;
const VOICE_CHANNEL_RE = /звонок|zoom|зум|видеозвон|встреч/i;
const MONEY_FIX = 'Всё, что касается денег (бюджет, «дорого», стоимость, варианты под бюджет), — только звонком или в Zoom (правило владельца). В этом касании о деньгах не писать: предложить короткий созвон — «по стоимости удобнее голосом: созвонимся сегодня на 5 минут?». Если предложение созвониться в касании уже есть — второе не добавлять, а убрать слова о деньгах (прогон 15.11: в письме вышло два приглашения подряд).';

// Кружок — интрига и призыв к созвону (владелец 15.11, методика — «провокация»): идею,
// кейсы, сроки, условия — по телефону. Прогоны DeepSeek «Зерно» 15.11: кружки со списком
// идей, дедлайном «не позже 19 ноября» и правилами города.
const KRUG_DETAIL_RE = /(расскажу|покажу|объясню),? как |как сделать(,)? (так,? )?чтобы|чтобы (ваша )?вывеска не |не позже|не позднее|стартовать до|запустить до|успеть до|902-ПП|по правилам города|нельзя на фасаде|на фасаде нельзя|баннер на фасаде|делали (вывеск|букв)|для (кафе|бара|кофейни) «/i;
const KRUG_CALL_RE = /набер[её]мся|набрать?ся|созвон|по телефону|позвон|наберу|набрать вас/i;
const KRUG_MAX = 300;
const KRUG_FIX = 'Кружок — интрига и призыв к созвону, коротко (до 300 символов): повод → «появилась идея, уверен, она вас точно заинтересует» → «можем коротко набраться — всё объясню по телефону?». Саму идею, кейсы, сроки, условия и правила города — убрать, это по телефону.';

// «Каждый день ожидания сдвигает дату» — один раз на цепочку; повтор — давление (прогон 14.11).
const SHIFT_RE = /кажд[а-яё]* (рабоч[а-яё]* )?(день|дня)[^.!?]{0,40}сдвига/i;

// [{ touchpoint_number, fixes }]
const wordSet = (t) => new Set(String(t || '').toLowerCase().replace(/[^а-яёa-z0-9\s]/g, ' ').split(/\s+/).filter((w) => w.length > 3));
// Слова шаблона кружка (правило 73) — у всех кружков общие, сравниваем остальное (повод, идею).
const KRUG_TEMPLATE_WORDS = new Set('добрый день здравствуйте привет решил записать короткое видео связи появилась идея идеи уверен уверена точно заинтересует интересно можем коротко набраться набрать наберёмся всё объясню телефону созвониться созвонимся расскажу минут пару сегодня завтра удобно ваша ваше вашей вашему вашим вашего проекту проекта проект думал вспомнил'.split(' '));
function contentWords(set) { return new Set([...set].filter((w) => !KRUG_TEMPLATE_WORDS.has(w))); }
function overlap(a, b) {
  if (!a.size || !b.size) return 0;
  let k = 0;
  for (const w of a) if (b.has(w)) k++;
  return k / Math.min(a.size, b.size);
}

// Разбор «Котик» (15.11): менеджер «уложилась, сделала», а в касаниях то «смотрела», то «проверял».
const FIRST_PERSON_STEMS = ['проверил', 'проверял', 'понял', 'посчитал', 'разобрал', 'подготовил', 'смотрел',
  'посмотрел', 'подумал', 'решил', 'записал', 'набрал', 'слышал', 'хотел', 'готовил', 'отправлял', 'отправил',
  'сделал', 'нашёл', 'увидел', 'уточнил', 'обсудил', 'передал', 'договорился', 'уложился'];
const stemRe = (forms) => new RegExp(`(^|[^а-яё])(${forms.join('|')})(?=[^а-яё]|$)`, 'gi');
const MASC_RE = stemRe(FIRST_PERSON_STEMS.map((w) => w.replace('нашёл', 'нашел|нашёл')));
const FEM_RE = stemRe(FIRST_PERSON_STEMS.map((w) => (w === 'нашёл' ? 'нашла' : w === 'договорился' ? 'договорилась'
  : w === 'уложился' ? 'уложилась' : `${w}а`)));
// Пол менеджера — по его же словам в материалах (заметки менеджера, «Я (дата): …»).
const MANAGER_FEM_RE = /(^|[^а-яё])(я\s+)?(уложилась|сделала|отправила|отправляла|написала|позвонила|звонила|договорилась|подготовила|выслала|скинула|предложила|рассчитала|посчитала)(?=[^а-яё]|$)/i;
const MANAGER_MASC_RE = /(^|[^а-яё])я\s+(уложился|сделал|отправил|отправлял|написал|позвонил|звонил|договорился|подготовил|выслал|скинул|предложил|рассчитал|посчитал)(?=[^а-яё]|$)/i;
function managerGender(sourceText) {
  const s = String(sourceText || '');
  if (MANAGER_FEM_RE.test(s)) return 'f';
  if (MANAGER_MASC_RE.test(s)) return 'm';
  return null;
}
const MOSCOW_RE = /москв|мск([^а-яё]|$)|метро|м\.\s?[А-ЯЁ]|902-?пп/i;
const PP902_RE = /902/;
const INVENTED_ISSUES_RE = /(есть|нашл?[аи]?|нашёл|вижу|увидел[а]?) (пар[ау]|несколько|пару-тройку) (момент|нюанс|замечани)/i;

// Только от первого лица: «Марина передала», «он решил», «собственник посмотрел» — не про менеджера.
const THIRD_PERSON_RE = /^(он|она|оно|они|клиент|клиентка|собственник|руководитель|директор|управляющ[а-яё]*|кто|котор[а-яё]+|партн[её]р|дизайнер|монтажник[а-яё]*|бригада|юрист|технолог)$/i;
function firstPerson(text, re) {
  const out = [];
  for (const x of String(text || '').matchAll(re)) {
    const before = text.slice(0, x.index + x[1].length);
    const prev = (before.match(/([А-ЯЁа-яёA-Za-z-]+)[\s)]*$/) || [])[1];
    const sentenceStart = /(^|[.!?…\n]\s*|[—–-]\s*|\]\s*)$/.test(before);
    if (prev && !sentenceStart && (/^[А-ЯЁ]/.test(prev) || THIRD_PERSON_RE.test(prev))) continue;
    out.push(x[2]);
  }
  return out;
}

function findPlanIssues(messages, plan, sourceText = '') {
  const gender = managerGender(sourceText);
  const isMoscow = MOSCOW_RE.test(String(sourceText || ''));
  let shiftSaidIn = null;
  const krugSeen = [];
  const moscowOrUnknown = !NOT_MOSCOW_RE.test(String(sourceText || ''));
  const byN = new Map((plan || []).map((p) => [p.touchpoint_number, p]));
  const lastN = (plan || []).find((p) => p.last_chance)?.touchpoint_number;
  const out = [];
  (messages || []).forEach((m, i) => {
    const n = Number(m?.touchpoint_number ?? i + 1);
    const t = textOf(m);
    const fixes = [];
    const p = byN.get(n);
    if (p?.last_chance) {
      if (!LAST_CHANCE_RE.test(t)) fixes.push(`Это касание — «последний шанс»: попросить сказать как есть, чтобы не тратить время клиента. ${LAST_CHANCE_HINT}`);
    } else if (lastN && LAST_CHANCE_RE.test(t)) {
      fixes.push(`Вопрос «скажите как есть / есть ли шанс / не буду отвлекать» — только в последнем касании (${lastN}, «последний шанс»). Здесь — шаг этого касания.`);
    }
    const channel = String(m?.channel || byN.get(n)?.channel || '');
    if (MONEY_TALK_RE.test(t) && !VOICE_CHANNEL_RE.test(channel) && !/созвон|позвон|наберу|zoom|зум|сориентир/i.test(t.match(new RegExp('[^.!?]*(' + MONEY_TALK_RE.source + ')[^.!?]*', 'i'))?.[0] || '')) fixes.push(MONEY_FIX);
        // «В понедельник в 10:00 наберу вас» без вопроса — давление (прогон 14.11): спросить согласие.
    const callAnnounce = t.split(/(?<=[.!?])\s+/).find((x) => /(^|[^а-яё])(наберу|позвоню|перезвоню)([^а-яё]|$)/i.test(x) && !/\?|удобно|если|можно|хорошо|договорил|как и/i.test(x));
    if (callAnnounce) fixes.push(`Звонок объявлен без согласия клиента («${callAnnounce.slice(0, 80)}») — давление. Спросить: «Удобно, если наберу в понедельник утром?»`);
        if (SHIFT_RE.test(t)) {
      if (shiftSaidIn == null) shiftSaidIn = n;
      else fixes.push(`«Каждый день ожидания сдвигает дату» уже сказано в касании ${shiftSaidIn} — повтор давит. Здесь — только дата на день отправки, без этой фразы.`);
    }
        if (ALT_RE.test(t) && !RISK_RE.test(t)) fixes.push(COMPROMISE_FIX);
    if (moscowOrUnknown && UNLIT_RE.test(t)) fixes.push(MOSCOW_FIXES.unlit);
    // «Внутри» нужно, когда баннер предлагают поставить, а не когда спрашивают о его цене.
    if (moscowOrUnknown && BANNER_RE.test(t) && /успе|постав|размест|повес|к открытию|монтаж/i.test(t) && !INSIDE_RE.test(t)) fixes.push(MOSCOW_FIXES.banner);
    if (moscowOrUnknown && BOX_RE.test(t) && !INLAY_RE.test(t)) fixes.push(MOSCOW_FIXES.box);
    // «Не отвлекаю в выходной?» — только если касание правда уходит в выходной (прогон 15.11: в среду).
    if (/в выходной|выходной день/i.test(t) && p?.send_date && isWorkingDay(p.send_date)) {
      fixes.push('Касание уходит в рабочий день — убрать «не отвлекаю в выходной?» и подобное про выходной.');
    }
    // Кружки в одной цепочке не повторяют друг друга (прогон 16 ситуаций, 15.11: «Арка» —
    // три кружка одним шаблоном «подбирал похожие работы — появилась идея»).
    if (/кружок|видео/i.test(channel)) {
      const words = wordSet(t);
      // Повод/идея — без пометки «[Видео …]» и обращения по имени (оно у всех кружков одно).
      const idea = contentWords(wordSet(t.replace(/\[[^\]]*\]/g, ' ').replace(/^\s*[^,!?.\n]{1,30}[,!]/, ' ')));
      const twin = krugSeen.find((k) => overlap(k.words, words) >= 0.9 || (idea.size >= 3 && k.idea.size >= 3 && overlap(k.idea, idea) >= 0.5));
      if (twin) fixes.push(`Кружок почти дословно повторяет касание ${twin.n}. Другой повод — другая конкретная деталь проекта (дата открытия, козырёк, логотип, вопрос клиента) и другие слова; приглашение созвониться оставить.`);
      krugSeen.push({ n, words, idea });
    }
    // Кружок — одному человеку (владелец, живой «Зерно 10»: «как в кружке можно обращаться к обоим?»).
    if (/кружок|видео/i.test(channel) && /^\s*(\[[^\]]*\]\s*)?[А-ЯЁ][а-яё]+,\s*[А-ЯЁ][а-яё]+[,!]/.test(t)) {
      fixes.push('Кружок — видео в лицо одному человеку: обратиться к одному (по ситуации — к контакту или к ЛПР), второе имя убрать.');
    }
    // Кружок — интрига + призыв к созвону (правило 73).
    if (/кружок|видео/i.test(channel) && (KRUG_DETAIL_RE.test(t) || !KRUG_CALL_RE.test(t) || t.length > KRUG_MAX)) fixes.push(KRUG_FIX);
    // Род менеджера в глаголах от первого лица — один во всех касаниях.
    const masc = firstPerson(t, MASC_RE);
    const fem = firstPerson(t, FEM_RE);
    if (gender === 'f' && masc.length) fixes.push(`Менеджер — женщина (по её словам в материалах): «${masc.slice(0, 3).join('», «')}» → в женском роде («проверила», «поняла», «посчитала»).`);
    else if (gender === 'm' && fem.length) fixes.push(`Менеджер — мужчина (по его словам в материалах): «${fem.slice(0, 3).join('», «')}» → в мужском роде.`);
    else if (!gender && masc.length && fem.length) fixes.push(`В одном касании глаголы менеджера в разном роде («${masc[0]}» и «${fem[0]}») — привести к одному.`);
    // 902-ПП — только Москва; «есть пара моментов» — только реальные, из данных.
    if (PP902_RE.test(t) && !isMoscow) fixes.push('902-ПП — правила Москвы, а город объекта в данных не указан. Убрать 902-ПП: «посмотрю ваш макет по требованиям города, чтобы не пришлось переделывать» (или уточнить город).');
    if (INVENTED_ISSUES_RE.test(t) && !INVENTED_ISSUES_RE.test(String(sourceText || ''))) fixes.push('«Есть пара моментов» — обещание найденных проблем, которых в данных нет. Иначе: «посмотрю ваш макет по требованиям города — чтобы вывеску не пришлось переделывать».');
    if (fixes.length) out.push({ touchpoint_number: n, fixes });
  });
  return out;
}

function applyPlanChecks(verdict, messages, plan, sourceText = '') {
  const hits = findPlanIssues(messages, plan, sourceText);
  if (!hits.length || !verdict || typeof verdict !== 'object') return { verdict, hits };
  const reviewed = Array.isArray(verdict.messages_reviewed) ? verdict.messages_reviewed : (verdict.messages_reviewed = []);
  for (const h of hits) {
    let m = reviewed.find((x) => Number(x?.touchpoint_number) === h.touchpoint_number);
    if (!m) { m = { touchpoint_number: h.touchpoint_number }; reviewed.push(m); }
    m.verdict = 'НА ДОРАБОТКУ';
    m.code_checked = true;
    m.failed_criteria = [...new Set([...(m.failed_criteria || []), 'plan'])];
    m.fix_instructions = [m.fix_instructions, ...h.fixes].filter(Boolean).join(' ');
  }
  verdict.verdict = 'НА ДОРАБОТКУ';
  return { verdict, hits };
}

module.exports = { managerGender, findPlanIssues, applyPlanChecks, LAST_CHANCE_RE, ALT_RE, RISK_RE };
