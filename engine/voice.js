/**
 * Голос недоступен (владелец 15.11): «Голос в приоритете, если нет такой возможности —
 * другие каналы (методика говорит именно это)». Деньги (бюджет, «дорого», варианты под
 * бюджет) — звонком; но если клиент не берёт трубку / просит писать / неудобно говорить —
 * можно в переписке. Признак ищем в переписке и словах менеджера.
 */
const VOICE_BLOCKED_RE = new RegExp([
  'не\\s+(?:отвечает|отвечают|отвечала|отвечал|бер[её]т|берут|брал[аи]?|взял[аи]?)\\s+(?:на\\s+)?(?:звонк|трубк|телефон)',
  'не\\s+дозвон',
  'сбрасывает|сбросил[аи]?\\s+(?:звонок|вызов)',
  '(?:просит|просил[аи]?|попросил[аи]?)\\s+(?:только\\s+)?(?:писать|написать|в\\s+переписк|в\\s+мессенджер)',
  '(?:пишите|напишите)[^.!?\\n]{0,20}(?:не\\s+звоните|неудобно|не\\s+могу\\s+говорить)',
  '(?:не\\s+может|не\\s+могу|неудобно)\\s+говорить',
  'звонить\\s+(?:не\\s+надо|неудобно|не\\s+нужно)',
  'не\\s+звоните',
  'только\\s+(?:в\\s+)?(?:переписк|мессенджер|whatsapp|ватсап|вотсап|телеграм)',
].join('|'), 'i');

function voiceBlocked(sourceText) {
  return VOICE_BLOCKED_RE.test(String(sourceText || ''));
}

// Скидка цифрой — только голосом (правило 77), даже если голос недоступен.
const DISCOUNT_FIGURE_RE = /скидк[^.!?\n]{0,30}\d+\s*%|\d+\s*%[^.!?\n]{0,20}скидк/i;

module.exports = { voiceBlocked, VOICE_BLOCKED_RE, DISCOUNT_FIGURE_RE };
