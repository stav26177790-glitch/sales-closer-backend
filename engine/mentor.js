/**
 * Режим «Наставник» (владелец 18.11): под каждым касанием — «почему так» одной-тремя короткими строками,
 * со ссылкой на методику владельца. Новичок видит не только ЧТО писать, но и ЗАЧЕМ.
 *
 * Собирается КОДОМ из плана касания (цель, критерий формулы, сценарий, подсказки писателю, последний шанс,
 * условие) — без лишнего вызова модели и без выдумок: показываем то, по чему касание реально построено.
 */

const SCENARIO_WHY = {
  negative: 'Клиент в эмоциях — по ВПР: выслушать, поддержать, спросить, как он видит выход; без оправданий, без «да, но» и без продажи (Негативная фаза)',
  torg: 'Торг — сигнал к покупке: уступка только через полномочия («согласую с руководителем») и в обмен на шаг — оплату / подписание (Возражения)',
  dorogo: '«Дорого»: сначала «в целом решение подходит?», потом — какое «дорого» (не нужно сейчас / не рассчитывали / поторговаться); в переписке — коротко, кружок или фото вариантов (Возражения, Переписка)',
  just_price: '«Просто цену»: даём ориентир и объясняем, почему точнее после короткого разбора — экономим клиенту время (Zoom)',
  think_now: '«Я подумаю» — не отпускаем в «жду звонка»: одна техника (в целом подходит? / нюанс-риск / в открытую), вопрос к истинному возражению и договорённость с датой (Возражения)',
  think_silence: '«Подумаю» → тишина: мягко вернуть в диалог вопросом о том, что мешает решить, и дать повод ответить (Возражения)',
  why_us: '«Чем вы отличаетесь»: 3 причины через «в отличие от…, иначе…» и выгоду клиента, а не общие слова; и доказательство делом — приглашение на производство (Отстройка)',
  want_see: 'Хочет посмотреть: показываем результат — визуализацию, образцы, встречу на производстве (Zoom)'
};

const HOW_WHY = [
  [/ПРЕДВОСХИЩЕНИЕ/, 'Предвосхищение: называем за клиента то, что у него на уме, вопросом-«да» — он соглашается и возражение теряет силу (Возражения)'],
  [/вплести (один вопрос|до \d+ вопрос)/, 'Вопрос по несобранному блоку СОПРАНО: ответ «разговорит» клиента и двинет формулу закрытия (СОПРАНО)'],
  [/ИДЕЯ ИЗ КРУЖКА/, 'Кружок создал интригу «появилась идея» — звонок её раскрывает: приглашение на производство, увидеть своими глазами (Отстройка)'],
  [/ЛДПР/, 'Адресат — не ЛПР: аккуратно выяснить его влияние («а если бы вы выбирали?»), к ЛПР — вместе с ним (ЛДПР)'],
  [/ПРИГЛАШЕНИЕ В ZOOM/, 'Zoom продаём как выгоду: «вслепую не посчитать точно — за 15 минут покажу варианты»; камера не обязательна (Zoom)'],
  [/СЦЕНАРИЙ ZOOM/, 'На Zoom — рамка «пройдёмся → покажу варианты → предложу шаг», в конце — договорённость с датой (Zoom)'],
  [/FOLLOW-UP/, 'После разговора — письменный итог «резюмирую: договорились…, ок?»: фиксирует договорённости, 90% менеджеров этого не делают (Переписка)'],
  [/заведующий производством|на производств/i, 'Встреча на производстве — сильнейший шаг доверия: клиент своими глазами видит, кто и как делает его вывеску (Zoom)']
];

const CRIT_NAME = { 'ФВ': 'финансовая возможность', 'ОП': 'осознанная потребность', 'ЛПР': 'выход на ЛПР', 'Д': 'доверие', 'ЗС': 'решение здесь и сейчас' };

const LAST_CHANCE_WHY = 'Последний шанс: финально и открыто — «скажите как есть»; при «нет» — «что я сделал не так?»: дверь остаётся открытой, а мы получаем обратную связь (Последний шанс)';

const KIND_WHY = {
  'эмпатичное': 'тон — эмпатичный: сначала человек, потом дело',
  'экспертное': 'тон — экспертный: польза и конкретика'
};

function short(text, max = 170) {
  const t = String(text || '').replace(/\s+/g, ' ').trim();
  if (t.length <= max) return t;
  const cut = t.slice(0, max).lastIndexOf(' ');
  return `${t.slice(0, cut > 60 ? cut : max)}…`;
}

/** Строки «почему так» для одного касания плана. Пусто — если плана нет. */
function mentorWhy(p) {
  if (!p || typeof p !== 'object') return [];
  const out = [];
  if (p.last_chance) out.push(LAST_CHANCE_WHY);
  else {
    const goal = String(p.goal || '').split(/\s*Заодно \(/)[0].split(/\s*Инструмент доверия:/)[0];
    const crit = p.criterion ? String(p.criterion).split(' —')[0] : '';
    const critName = CRIT_NAME[crit] || '';
    if (goal) out.push(`Цель: ${short(goal).replace(/[.;,]\s*$/, '')}${crit ? ` — двигаем «${crit}${critName ? ` (${critName})` : ''}» в формуле закрытия` : ''}`);
  }
  for (const id of p.scenarios || []) if (SCENARIO_WHY[id]) out.push(SCENARIO_WHY[id]);
  const how = String(p.how || '');
  for (const [re, why] of HOW_WHY) if (re.test(how) && out.length < 4) out.push(why);
  if (p.condition && out.length < 4) out.push(`Отправлять, только если ${String(p.condition).replace(/^только если:?\s*/i, '')} — иначе касание не к месту`);
  const tone = KIND_WHY[String(p.kind || '').toLowerCase()];
  if (tone && !p.last_chance && out.length && out.length < 4) out[0] = `${out[0]}; ${tone}`;
  if (out[0] && /^Цель:.*в формуле закрытия/.test(out[0])) out[0] = `${out[0]} (Формула закрытия)`;
  return out.slice(0, 4);
}

module.exports = { mentorWhy, SCENARIO_WHY };
