/**
 * Отсев ложных находок проверки грубых ошибок — общий для Клоузера (agents/critic, autoCompose.criticalGate)
 * и судьи симулятора (tests/eval/run.js). Модель-проверяющий иногда ставит ошибку на правильный ход владельца;
 * в Клоузере это значит «переписать хорошее касание» — поэтому очевидные ложные находки код убирает.
 * Прогоны экзамена 17.11 (4–7): каждое правило ниже — реальная ложная находка.
 */
const { voiceBlocked } = require('./voice');

const errNo = (c) => String(c?.error || '').match(/^\s*(\d)/)?.[1] || (/обещани[ея] срока/i.test(String(c?.error || '')) ? '2' : /деньги письменно/i.test(String(c?.error || '')) ? '6' : null);

function keepCritical(c, { source = '', status = '' } = {}) {
  const q = String(c?.quote || '');
  switch (errNo(c)) {
    case '1': // честный торг по сценарию владельца: «N не смогу / нет полномочий / небольшая уступка за шаг», цена КП.
      // Прогон 8: «мы согласовали уступку — подписываем» без суммы — не ошибка. Ошибка — цена клиента / «договорились».
      if (!/(?<![\d.,])\d{3}(?:[ \u00a0]?\d{3})?(?!\s*%|\d)|договорились|уже уступка/i.test(q)) return false; // сумма, не «50%»
      return !(/небольш[а-яё]* уступк|полномочи|не смогу|не выйдет|наличн|табличк|70\s*\/\s*30/i.test(q) && !/договорились|уже уступка|по цене \d|согласов[а-яё]* с руководител[а-яё]*\.?\s*если получится/i.test(q));
    case '2': // только обещание к открытию при «не успеваем»; честная дата, временная вывеска, «впритык / с запасом» — не ошибка
      if (/с запасом|впритык/i.test(String(status || ''))) return false;
      return /к открыт|успева|успеем|к \d{1,2} (ноябр|декабр|январ)/i.test(q) && !/не успева|уже не|позже|временн/i.test(q);
    case '3': // упрёк — только с маркерами упрёка; «Помните, мы проговаривали…», «понимаю, почему вы осторожны» — нет
      if (/помните,? мы (проговаривали|договаривались)|мы с вами договаривались/i.test(q)) return false;
      return /обещал|так и не|тишина|не (ответили|перезвонили|прислали|набрали)|пропал|сами (назвали|сказали)/i.test(q);
    case '7': // «приедет наш специалист», «заведующий покажет» — верно; ошибка — менеджер сам едет / везёт
      return /я (сама?|тоже)? ?(приеду|привезу|подъеду)|у меня с собой|привезу|сама? покажу цех/i.test(q);
    case '6': // голос недоступен на момент хода — деньги в переписке можно
      return !voiceBlocked(source);
    default:
      return true;
  }
}

module.exports = { keepCritical, errNo };
