/**
 * Сценарии владельца для критичных ситуаций (engine/scenarios.js, владелец 17.11).
 */
const assert = require('assert');
const { detectScenarios, attachScenarios, checkScenario } = require('../engine/scenarios');
const { SCENARIOS } = require('../engine/scenarios');
let n = 0;
function check(name, fn) { fn(); n++; console.log(`  ✓ ${name}`); }
const ids = (src) => detectScenarios(src).map((s) => s.id).sort();
const addHow = (x, t) => { x.how = [...(x.how || []), t]; };

check('ситуация — по последнему событию', () => {
  assert.deepEqual(ids('Арсен: «Сделаете 650 — и платим 50% сразу, подписываем до пятницы».'), ['torg']);
  assert.deepEqual(ids('Ольга: Игорь Петрович посмотрел КП: дороговато — нам предлагают за 480.'), ['dorogo']);
  assert.deepEqual(ids('Вика: зачем нам какой-то Zoom, просто скиньте цену без логотипа.'), ['just_price']);
  assert.deepEqual(ids('Арсен сказал, что подумает до понедельника. Понедельник прошёл, не перезвонил.'), ['think_silence']);
  assert.deepEqual(ids('Георгий Давидович хочет сначала своими глазами посмотреть, как делают буквы.'), ['want_see']);
  assert.deepEqual(ids('Тамара: Спасибо, покажу Георгию Давидовичу.'), []);
});
check('карточка — в how голосового касания-ответа', () => {
  const steps = [{ channel: 'WhatsApp', kind: 'экспертное' }, { channel: 'Звонок', kind: 'экспертное' }];
  attachScenarios(steps, 'Арсен: «Сделаете 650 — подпишем».', addHow);
  assert.ok(!steps[0].how && /СЦЕНАРИЙ «ТОРГ»/.test(steps[1].how[0]) && /«650 — точно не смогу/.test(steps[1].how[0]));
  assert.deepEqual(steps[1].scenarios, ['torg']);
});
check('проверка ходов: торг без полномочий и уступки — на правку; по сценарию — ок; в мессенджере — позвать к разговору', () => {
  assert.equal(checkScenario('Арсен, давайте подпишем по 690.', ['torg'], { channel: 'Звонок' }).length, 1);
  assert.equal(checkScenario('650 — точно не смогу, у меня таких полномочий нет. Попробую согласовать 5% за наличные, если подписываем до пятницы.', ['torg'], { channel: 'Звонок' }).length, 0);
  assert.equal(checkScenario('По цене удобнее голосом — созвонимся сегодня на 5 минут?', ['torg'], { channel: 'WhatsApp' }).length, 0);
  assert.equal(checkScenario('Пятница прошла, от вас тишина. Что изменилось?', ['think_silence']).length, 1);
  assert.equal(checkScenario('Мы с вами договаривались созвониться после понедельника — как ваше решение?', ['think_silence']).length, 0);
  assert.equal(checkScenario('Я привезу образец прямо к вам.', ['want_see'], { channel: 'Звонок' }).length, 1);
});
check('прогон 6: сценарии — только по последнему сообщению менеджера; тишина вытесняет старые; торг и «посмотреть» — в разные звонки', () => {
  const src = '[Сообщение менеджера 1]\nВика: зачем нам Zoom, просто скиньте цену.\n\n[Сообщение менеджера 2]\nок\n\n[Сообщение менеджера 3]\nПровела Zoom. Арсен: «Сделаете 650 — подписываем до пятницы». Хочет потрогать латунь вживую.';
  assert.deepEqual(ids(src), ['torg', 'want_see']);
  assert.deepEqual(ids(src + '\n\n[Сообщение менеджера 4]\nАрсен обещал подумать до понедельника. Понедельник прошёл, не перезвонил. Сделаете 650 — помним.'), ['think_silence']);
  const steps = [{ channel: 'Звонок' }, { channel: 'WhatsApp' }, { channel: 'Звонок', conditional: true }];
  attachScenarios(steps, src, addHow);
  assert.deepEqual(steps[0].scenarios, ['torg']); assert.deepEqual(steps[2].scenarios, ['want_see']);
});
check('шероховатости 1, 3, 4: следующий шаг — ответ на событие в касании 1 (торг — звонок); «договор у меня с собой»; «так и не подписан»', () => {
  const steps = [{ channel: 'WhatsApp', kind: 'эмпатичное' }, { channel: 'Звонок', kind: 'экспертное' }];
  attachScenarios(steps, 'Арсен: «Сделаете 650 — подписываем до пятницы». Хочет потрогать латунь.', addHow, { step: true, voiceOk: true });
  assert.deepEqual(steps[0].scenarios, ['torg']); assert.deepEqual(steps[1].scenarios, ['want_see']);
  assert.equal(checkScenario('Договор у меня с собой — подписываем?', ['want_see'], { channel: 'Личная встреча' }).length, 1);
  assert.equal(checkScenario('Мы обсуждаем с 6 ноября, а договор так и не подписан.', ['think_silence']).length, 1);
});
check('владелец 17.11, файл 31: негатив клиента — сценарий «Негатив» первым; «да, но» и аргументы без поддержки — на правку', () => {
  const src = '[Сообщение менеджера 1]\nКлиент: «Вы отнимаете моё время, я потратил на вас 10 минут впустую! Дорого и долго».';
  assert.equal(detectScenarios(src)[0].id, 'negative');
  assert.equal(checkScenario('Понимаю вас, Сергей!) Ценю ваш деловой подход. Давайте сориентирую по вилке цен, могу так?', ['negative']).length, 0);
  assert.equal(checkScenario('Да, но у нас свой цех и договор.', ['negative']).length, 1);
  assert.equal(checkScenario('Спасибо, что сказали прямо. Однако сроки были в договоре — как вы видите выход?', ['negative']).length, 1);
  // экзамен 5: поддержка есть, но сразу продажа и без вопроса о видении — на правку
  assert.equal(checkScenario('Ирина Викторовна, вы правы, это моя ошибка, понимаю вас. Что скажете по цене и макету?', ['negative']).length, 1);
  assert.equal(checkScenario('Вы правы, это моя ошибка, понимаю вас. Правильно понимаю, что главное — успеть к 20-му? Как вы видите правильный выход?', ['negative']).length, 0);
  // негатив, а потом тишина — уже «подумает → тишина»
  assert.deepEqual(ids(src + '\n\n[Сообщение менеджера 2]\nОбещал подумать до пятницы. Пятница прошла, тишина.'), ['think_silence']);
  assert.ok(!ids('[Сообщение менеджера 1]\nКлиент: в целом нравится, подумаем до понедельника.').includes('negative'));
});
check('владелец 18.11, файл 26: «дорого» в переписке — без длинного перечня; в звонке — можно', () => {
  const long = 'Марат, что вы получаете за 128 000 ₽:\n— световые буквы;\n— табличку;\n— монтаж;\n— проверку по 902-ПП.\nКакое «дорого» — не рассчитывали или поторговаться?';
  assert.ok(checkScenario(long, ['dorogo'], { channel: 'Telegram', voiceOk: false }).some((f) => /длинные обоснования/.test(f)));
  assert.ok(!checkScenario(long, ['dorogo'], { channel: 'Звонок' }).some((f) => /длинные обоснования/.test(f)));
  assert.ok(!checkScenario('Алина, отправила фото двух вариантов в рамках правил города. Какой вам ближе — не рассчитывали на сумму или поторговаться?', ['dorogo'], { channel: 'Telegram', voiceOk: false }).some((f) => /длинные обоснования/.test(f)));
});
check('владелец 18.11, файл 32: «чем вы отличаетесь / то же самое дешевле» — сценарий «Почему мы»; картинки без отстройки — на правку', () => {
  const src = '[Сообщение менеджера 2]\nСергей Петрович: Покажите, чем вы отличаетесь. Только без воды. Другие делают то же самое, только дешевле.';
  assert.ok(ids(src).includes('why_us'));
  assert.equal(checkScenario('Сергей Петрович, вот вывеска для автосервиса. Как вам?', ['why_us']).length, 1);
  assert.equal(checkScenario('Три вещи: проработанный проект под ваш объект — в отличие от многих, дата не уедет. Приезжайте в цех в Мытищах — пятница в 11?', ['why_us']).length, 0);
});
check('владелец 18.11, файл 33: «я подумаю и сам перезвоню» — сценарий «Я подумаю»; «буду ждать звонка» — на правку; карточки с предвосхищением', () => {
  assert.deepEqual(ids('[Сообщение менеджера 1]\nСергей Петрович: Посмотрел. Я подумаю и сам перезвоню.'), ['think_now']);
  assert.deepEqual(ids('[Сообщение менеджера 1]\nОбещал подумать до пятницы. Пятница прошла, тишина.'), ['think_silence']);
  assert.equal(checkScenario('Сергей Петрович, понял вас. Буду ждать вашего звонка.', ['think_now']).length, 1);
  assert.equal(checkScenario('Конечно. А в целом подходит, или есть моменты, которые смущают? Наберу в четверг в 11 — удобно?', ['think_now']).length, 0);
  assert.ok(/ПРЕДВОСХИЩЕНИЕ/.test(SCENARIOS.find((x) => x.id === 'dorogo').card()));
});
check('«Почему мы» живёт в пути, пока клиент не увидел отстройку (не приехал, тишина); приехал / понравилось — снимается', () => {
  const src = '[Сообщение менеджера 2]\nСергей Петрович: Покажите, чем вы отличаетесь. Без воды.\n\n[Сообщение менеджера 3]\nДоговорились на пятницу, не приехал, тишина 4 дня.';
  assert.ok(ids(src).includes('why_us'));
  assert.ok(!ids(src + '\n\n[Сообщение менеджера 4]\nПриехал в цех, всё понравилось.').includes('why_us'));
});
check('«Почему мы»: клиент не поверил «ОТК, гарантиям» — повторять их причинами нельзя; экспертиза + ведение + показ — ок', () => {
  const src = 'Сергей Петрович: у всех одинаково, вы мне очки втираете со своим ОТК, гарантиями и визуализациями.';
  const bad = 'Три вещи: своё производство — в отличие от многих, срок не уедет. ОТК проверяет. Гарантия в договоре. Словам верить не обязаны — приезжайте в цех в Мытищах.';
  const good = 'Вы получаете проработанный проект под ваш бокс — многие делают по макету, иначе въезд не видно. Ведёт один человек от макета до монтажа. Словам верить не обязаны — приезжайте в цех в Мытищах, там и ОТК покажу.';
  assert.equal(checkScenario(bad, ['why_us'], { source: src }).length, 1);
  assert.equal(checkScenario(good, ['why_us'], { source: src }).length, 0);
});
console.log(`scenarios: ${n} проверок пройдено`);
