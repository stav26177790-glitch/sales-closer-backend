/**
 * База знаний без выдуманных фактов о компании (владелец 15.11: «выдуманные не нужно,
 * у нас и так есть сильные ходы»). Проверяем файлы knowledge/, которые видят агенты
 * (llm/registry.js), — кроме industry/* (там реальные факты и списки «чего нельзя»).
 * Факты компании — только из knowledge/industry/signage.md и КП.
 */
const assert = require('assert');
const fs = require('fs');
const path = require('path');
const { AGENTS } = require('../llm/registry');

let n = 0;
function check(name, fn) { fn(); n++; console.log(`  ✓ ${name}`); }

const DIR = path.join(__dirname, '..', 'knowledge');
const files = [...new Set(Object.values(AGENTS).flatMap(a => a.knowledge || []))];

// Выдумки, найденные 15.11 при проверке базы, — не должны вернуться.
const BANNED = [
  [/samsung/i, 'марка диодов (нет в фактах компании)'],
  [/гаранти[яию]\s+\d+\s*(год|лет)/i, 'гарантия N лет (только по договору, по бренду)'],
  [/1 год вместо 3/i, 'урезание гарантии как способ удешевить'],
  [/48 час/i, 'выезд за 48 часов (по факту — 3 рабочих дня)'],
  [/штраф\w*\s+\d+\s*[-–]\s*\d+\s*тысяч/i, 'сумма штрафа (без сумм и пугалок)'],
  [/\(\s*\d+\s*[-–]\s*\d+\s*тысяч\s*\)/i, 'сумма демонтажа'],
  [/срочн\w+ (режим|монтаж)[^.\n]{0,40}(доплат|без доплаты)/i, 'срочный режим / монтаж (ускоренного нет)'],
  [/стандартный срок \d+ рабочих/i, 'стандартный срок N дней (срок — из КП)'],
  [/ему \d+ (год|лет)/i, 'возраст объекта-примера'],
  [/работаем [^.\n]{0,30}\d+ лет/i, 'опыт N лет (только цифры бренда из signage.md)'],
  [/снижает издержки на \d+%/i, 'выдуманная статистика'],
  [/контакт Ирины/i, 'выдуманный именной кейс'],
  [/старую цену/i, '«старая цена» (цена КП держится 2 месяца)'],
  [/не уйд[её]т в производство/i, '«иначе не уйдёт в производство» (вместо этого — слот)'],
  [/бесплатно при заказе сегодня/i, 'бонус «только сегодня»'],
];

check(`в базе для агентов (${files.length} файлов) нет выдуманных фактов о компании`, () => {
  const found = [];
  for (const f of files) {
    const p = path.join(DIR, f);
    if (!fs.existsSync(p)) continue;
    const text = fs.readFileSync(p, 'utf8');
    for (const [re, why] of BANNED) {
      const m = text.match(re);
      if (m) found.push(`${f}: «${m[0]}» — ${why}`);
    }
  }
  assert.deepEqual(found, []);
});

check('проверка ловит выдумку (самопроверка словаря)', () => {
  const sample = 'акрил 10 мм, диоды Samsung, гарантия 3 года; штраф 50-150 тысяч; могу предложить старую цену';
  const hits = BANNED.filter(([re]) => re.test(sample)).length;
  assert.ok(hits >= 4, `поймано ${hits}`);
});

console.log(`knowledgeFacts: ${n} проверок пройдено`);
