'use strict';
const assert = require('assert');
const { voiceBlocked } = require('../engine/voice');
let n = 0;
const check = (name, fn) => { fn(); n++; console.log(`  ✓ ${name}`); };
check('прогон 18.11 «Гибкость»: «телефона нет», «созваниваться некогда, пишите здесь» — голос недоступен', () => {
  assert.ok(voiceBlocked('Заявка пришла в Telegram с сайта, телефона нет.'));
  assert.ok(voiceBlocked('Алина: Сколько стоит? Пришлите КП, созваниваться некогда.'));
  assert.ok(voiceBlocked('Говорит, давайте без подсветки. Созваниваться некогда, пишите здесь.'));
  assert.ok(voiceBlocked('Мне некогда говорить, пишите.'));
});
check('после созвона голос снова доступен; обычная переписка — голос доступен', () => {
  assert.ok(!voiceBlocked('Созваниваться некогда, пишите здесь. … Созвонилась с Маратом, ему нравится визуализация.'));
  assert.ok(!voiceBlocked('Алина: спасибо, посмотрю КП и отвечу.'));
  assert.ok(!voiceBlocked('Позвоните мне завтра, сейчас некогда.')); // «сейчас некогда» — не отказ от голоса
});
console.log(`voice: ${n} проверок пройдено`);
